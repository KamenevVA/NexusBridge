import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir,mkdtemp,readFile,writeFile,rm } from 'node:fs/promises';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { makeMvp } from '../src/mvp-core.ts';
const sha=(b:Buffer|string)=>createHash('sha256').update(b).digest('hex');
test('G1 binary pagination, canonical input and atomic ordered patch',async t=>{
  await mkdir(join(process.cwd(),'.runtime'),{recursive:true});
  const base=await mkdtemp(join(process.cwd(),'.runtime','fs-extension-'));
  const root=join(base,'workspace'),checkpointRoot=join(base,'checkpoints');
  await mkdir(root);await mkdir(checkpointRoot);
  const logs:object[]=[];
  const m=await makeMvp({root,checkpointRoot,write:true,exec:false,commands:{},assertActive:async()=>{},audit:async e=>{logs.push(e);}});
  const [a,b]=InMemoryTransport.createLinkedPair(),c=new Client({name:'fs-test',version:'0.1.0'});
  t.after(async()=>{await c.close();await m.stop();await rm(base,{recursive:true,force:true});});
  await m.server.connect(a);await c.connect(b);
  const raw=(name:string,args:Record<string,unknown>)=>c.callTool({name,arguments:args});
  async function call(name:string,args:Record<string,unknown>){const r=await raw(name,args);assert.equal(r.isError??false,false,JSON.stringify(r));return JSON.parse((r.content as Array<{text:string}>)[0].text);}
  const bytes=Buffer.from([0,255,1,128,64,10]);
  assert.equal((await call('write_binary_file',{path:'sample.bin',base64:bytes.toString('base64'),expectedHash:null})).sha256,sha(bytes));
  const first=await call('read_binary_file',{path:'sample.bin',length:3});
  const second=await call('read_binary_file',{path:'sample.bin',offset:first.nextOffset,length:3});
  assert.equal(first.nextOffset,3);assert.equal(second.nextOffset,null);
  assert.deepEqual(Buffer.concat([Buffer.from(first.base64,'base64'),Buffer.from(second.base64,'base64')]),bytes);
  assert.equal(first.sha256,sha(bytes));assert.equal(second.sha256,sha(bytes));
  assert.equal((await raw('read_file',{path:'sample.bin'})).isError,true);
  for(const base64 of ['AB==','YQ','Y Q==','____'])assert.equal((await raw('write_binary_file',{path:'bad.bin',base64,expectedHash:null})).isError,true);
  assert.equal((await raw('write_binary_file',{path:'sample.bin',base64:'YQ==',expectedHash:null})).isError,true);
  assert.equal((await raw('read_binary_file',{path:'sample.bin',offset:7})).isError,true);
  const replaced=await call('write_binary_file',{path:'sample.bin',base64:'YQ==',expectedHash:sha(bytes)});
  assert.deepEqual(await readFile(join(checkpointRoot,replaced.checkpointId+'.bak')),bytes);
  const original=Buffer.from('\uFEFFalpha\r\nbeta\r\n','utf8');
  await writeFile(join(root,'text.txt'),original);
  const edits=[{oldText:'alpha',newText:'one'},{oldText:'beta',newText:'two'}];
  assert.equal((await raw('apply_patch',{path:'text.txt',edits:[edits[0],{oldText:'absent',newText:'x'}],expectedHash:sha(original)})).isError,true);
  assert.deepEqual(await readFile(join(root,'text.txt')),original);
  const patched=await call('apply_patch',{path:'text.txt',edits,expectedHash:sha(original)});
  assert.deepEqual(await readFile(join(root,'text.txt')),Buffer.from('\uFEFFone\r\ntwo\r\n'));
  assert.deepEqual(await readFile(join(checkpointRoot,patched.checkpointId+'.bak')),original);
  assert.equal((await raw('apply_patch',{path:'text.txt',edits,expectedHash:sha(original)})).isError,true);
  await writeFile(join(root,'overlap.txt'),'aaa');
  assert.equal((await raw('apply_patch',{path:'overlap.txt',edits:[{oldText:'aa',newText:'x'}],expectedHash:sha('aaa')})).isError,true);
  assert.equal((await raw('edit_file',{path:'overlap.txt',oldText:'aa',newText:'x',expectedHash:sha('aaa')})).isError,true);
  assert.ok(logs.some(e=>JSON.stringify(e).includes('apply_patch_ok')));
});
