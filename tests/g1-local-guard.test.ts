import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdir,mkdtemp,writeFile,readFile,rm,unlink,link} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {randomUUID} from 'node:crypto';
import {createLocalGuard} from '../src/g1-local-guard.ts';
import {approveSynthetic} from './helpers/local-approval.ts';
test('exact local approval: bound arguments, one-use, expiry, fail closed stop',async t=>{
  await mkdir(resolve('.runtime'),{recursive:true});
  const base=await mkdtemp(join(resolve('.runtime'),'guard-test-')),controlRoot=join(base,'control'),pendingRoot=join(base,'pending');
  await mkdir(controlRoot);await mkdir(pendingRoot);t.after(()=>rm(base,{recursive:true,force:true}));
  const guard=await createLocalGuard({sessionId:randomUUID(),controlRoot,pendingRoot});
  const details={template:'synthetic',args:['one','two'],input:false};
  const req=await guard.check('start_process',details);
  assert.equal(req.status,'awaiting_approval');
  assert.equal((await guard.check('start_process',{input:false,args:['one','two'],template:'synthetic'})).approvalId,req.approvalId);
  assert.equal((await guard.check('start_process',details,req.approvalId)).status,'awaiting_approval');
  await assert.rejects(guard.check('start_process',{...details,args:['changed']},req.approvalId),/mismatched/);
  const path=join(controlRoot,req.approvalId+'.json'),p=JSON.parse(await readFile(join(pendingRoot,req.approvalId+'.json'),'utf8'));
  await writeFile(path,JSON.stringify({v:1,id:p.id,sessionId:p.sessionId,digest:'0'.repeat(64),expiresAt:p.expiresAt}),{flag:'wx'});
  await assert.rejects(guard.check('start_process',details,req.approvalId),/not valid/);
  await unlink(path);await approveSynthetic(base,req);
  assert.equal((await guard.check('start_process',details,req.approvalId)).status,'approved');
  await assert.rejects(guard.check('start_process',details,req.approvalId),/consumed/);
  const second=await guard.check('trash_file',{path:'synthetic.txt',expectedHash:'1'.repeat(64)});
  await approveSynthetic(base,second);await link(join(controlRoot,second.approvalId+'.json'),join(base,'linked-approval'));
  await assert.rejects(guard.check('trash_file',{path:'synthetic.txt',expectedHash:'1'.repeat(64)},second.approvalId),/Unsafe/);
  await writeFile(join(controlRoot,'stop.flag'),'STOP',{flag:'wx'});
  await assert.rejects(guard.assertActive(),/emergency stop/);
  await unlink(join(controlRoot,'stop.flag'));await assert.rejects(guard.assertActive(),/stopped/);
  const expiry=await createLocalGuard({sessionId:randomUUID(),controlRoot,pendingRoot,ttlMs:100});
  const expired=await expiry.check('move_file',{source:'a',destination:'b'});
  await new Promise(r=>setTimeout(r,150));await assert.rejects(expiry.check('move_file',{source:'a',destination:'b'},expired.approvalId),/expired/);
});
